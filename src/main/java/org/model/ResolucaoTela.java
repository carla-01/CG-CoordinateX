package org.model;

public class ResolucaoTela {

    private int largura;
    private int altura;

    public ResolucaoTela(int largura, int altura) {
        this.largura = largura;
        this.altura = altura;
    }

    public int getLargura() {
        return largura;
    }

    public int getAltura() {
        return altura;
    }

}